-- ============================================
-- 工作台 Supabase 数据库迁移脚本
-- 在 Supabase SQL Editor 中执行此脚本即可
-- ============================================

-- 1. 创建数据表
CREATE TABLE IF NOT EXISTS workbench_data (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  workspace_id TEXT UNIQUE NOT NULL,
  data JSONB NOT NULL DEFAULT '{}'::jsonb,
  version INTEGER NOT NULL DEFAULT 0,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- 2. 创建索引（加速查询）
CREATE INDEX IF NOT EXISTS idx_workbench_data_workspace_id ON workbench_data(workspace_id);

-- 3. 启用行级安全策略（RLS）
ALTER TABLE workbench_data ENABLE ROW LEVEL SECURITY;

-- 4. 允许所有用户通过 anon key 读写（个人工作台场景，你的 workspace_id 就是密码）
CREATE POLICY "Allow all operations on workbench_data"
  ON workbench_data
  FOR ALL
  USING (true)
  WITH CHECK (true);

-- 5. 启用 Realtime 订阅（关键：实现多设备实时同步）
ALTER PUBLICATION supabase_realtime ADD TABLE workbench_data;
